const SERVER_NAME = 'conductor';
const MARKER = 'Generated by Skill Conductor';
const BUNDLE_PACKAGE_NAME = 'skill-conductor-mcp-bundle';
const CLI_BASENAME = 'skill-conductor.mjs';

export function hostInfo(host) {
  const info = HOSTS[host];
  if (!info) throw new ConfigError(`unsupported host: ${host}`);
  return info;
}

function yamlSingle(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function cordisPatch({ nodePath, cliPath, configPath }) {
  return [
    `# ${MARKER} setup. Local DeepSeek Harness MCP bundle patch.`,
    '# Cordis patch operation document: - insert: [entry]. Not mcpServers JSON.',
    '- insert:',
    '    - id: mcp-skill-conductor',
    "      name: '@deepseek-ai/dsh-mcp-client'",
    '      config:',
    '        serverName: skill-conductor',
    '        transport: stdio',
    `        command: ${yamlSingle(nodePath)}`,
    '        args:',
    `          - ${yamlSingle(cliPath)}`,
    "          - 'mcp'",
    `          - ${yamlSingle('--config')}`,
    `          - ${yamlSingle(configPath)}`,
    '        failOnStartupError: true',
    '',
  ].join('\n');
}

function bundlePackage() {
  return `${JSON.stringify(
    {
      name: BUNDLE_PACKAGE_NAME,
      version: PRODUCT_VERSION,
      private: true,
      type: 'module',
      description: 'Generated by Skill Conductor. Local DeepSeek Harness MCP bundle.',
      files: ['cordis.patch.yml'],
      dsh: { bundle: { patch: './cordis.patch.yml' } },
    },
    null,
    2,
  )}\n`;
}

function serverFor(host, paths) {
  if (host === 'opencode') {
    return {
      type: 'local',
      command: [paths.nodePath, paths.cliPath, 'mcp', '--config', paths.configPath],
      codemode: false,
      protocol: 'legacy',
    };
  }
  return {
    command: paths.nodePath,
    args: [paths.cliPath, 'mcp', '--config', paths.configPath],
  };
}

function containerFor(host, raw) {
  if (host === 'opencode') {
    const root = raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : {};
    const mcp = root.mcp && typeof root.mcp === 'object' && !Array.isArray(root.mcp) ? root.mcp : {};
    const servers =
      mcp.servers && typeof mcp.servers === 'object' && !Array.isArray(mcp.servers) ? mcp.servers : {};
    return { root, mcp, servers };
  }
  const root = raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : {};
  const servers =
    root.mcpServers && typeof root.mcpServers === 'object' && !Array.isArray(root.mcpServers)
      ? root.mcpServers
      : {};
  return { root, servers };
}

function launchFor(host, server) {
  if (!server) return null;
  if (host === 'opencode' && Array.isArray(server.command)) {
    return { command: server.command[0], args: server.command.slice(1) };
  }
  if (typeof server.command === 'string' && Array.isArray(server.args)) {
    return { command: server.command, args: server.args };
  }
  return null;
}

function serverLooksOwned(host, server) {
  const launch = launchFor(host, server);
  if (!launch) return false;
  return (
    launch.args.some((arg) => String(arg).endsWith(CLI_BASENAME)) &&
    launch.args.some((arg) => String(arg) === 'mcp' || String(arg) === '--mcp')
  );
}

function findOwnedServer(host, raw) {
  const { servers } = containerFor(host, raw);
  for (const [name, server] of Object.entries(servers)) {
    if (serverLooksOwned(host, server)) return { name, server };
  }
  return null;
}

function chooseServerName(host, raw) {
  const existing = findOwnedServer(host, raw);
  if (existing) return { name: existing.name, preservedConflict: false };
  const { servers } = containerFor(host, raw);
  if (!servers[SERVER_NAME]) return { name: SERVER_NAME, preservedConflict: false };
  const candidates = [`${SERVER_NAME}-skill-conductor`];
  for (let index = 2; index <= 50; index += 1) candidates.push(`${SERVER_NAME}-${index}`);
  for (const candidate of candidates) {
    if (!servers[candidate]) return { name: candidate, preservedConflict: true };
  }
  throw new ConfigError('too many conflicting MCP server names; no entry was written');
}

function mergedJson(host, raw, serverName, server) {
  if (host === 'opencode') {
    const { root, mcp, servers } = containerFor(host, raw);
    return {
      ...root,
      mcp: {
        ...mcp,
        servers: { ...servers, [serverName]: server },
      },
    };
  }
  const { root, servers } = containerFor(host, raw);
  return { ...root, mcpServers: { ...servers, [serverName]: server } };
}

async function assertProjectWrite(root, target) {
  const rootAbs = path.resolve(root);
  const targetAbs = path.resolve(target);
  if (!isInside(rootAbs, targetAbs)) throw new ConfigError(`host write escapes project: ${targetAbs}`);
  let current = rootAbs;
  const parts = path.relative(rootAbs, path.dirname(targetAbs)).split(path.sep).filter(Boolean);
  for (const part of parts) {
    current = path.join(current, part);
    try {
      const stat = await fs.lstat(current);
      if (stat.isSymbolicLink()) throw new ConfigError(`refusing symlink host path: ${current}`);
      if (!stat.isDirectory()) throw new ConfigError(`host path component is not a directory: ${current}`);
    } catch (error) {
      if (error.code === 'ENOENT') break;
      throw error;
    }
  }
  try {
    const stat = await fs.lstat(targetAbs);
    if (stat.isSymbolicLink()) throw new ConfigError(`refusing symlink host target: ${targetAbs}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

async function atomicWrite(file, text) {
  const temp = `${file}.tmp-${process.pid}-${globalThis.crypto.randomUUID().slice(0, 8)}`;
  await fs.writeFile(temp, text, 'utf8');
  try {
    await fs.rename(temp, file);
  } catch (error) {
    if (error.code === 'EEXIST' || error.code === 'EPERM' || error.code === 'EACCES') {
      await fs.unlink(file).catch(() => {});
      await fs.rename(temp, file);
    } else {
      await fs.unlink(temp).catch(() => {});
      throw error;
    }
  }
}

async function backupFile(file, now) {
  const stamp = now.toISOString().replace(/[-:.TZ]/g, '').slice(0, 15);
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const suffix = attempt === 0 ? '' : `-${attempt}`;
    const target = `${file}.bak-${stamp}${suffix}`;
    try {
      await fs.copyFile(file, target, fsConstants.COPYFILE_EXCL);
      return target;
    } catch (error) {
      if (error.code !== 'EEXIST') throw error;
    }
  }
  throw new ConfigError(`could not create a unique backup for ${file}`);
}

async function writePatch(cwd, host, payload, now, reason = null) {
  const dir = path.join(cwd, '.skill-conductor', 'patches');
  const file = path.join(dir, `${host}.mcp.patch.json`);
  await assertProjectWrite(cwd, file);
  await fs.mkdir(dir, { recursive: true });
  const patch = {
    schema: 'skill-conductor/host-patch/v1',
    generatedAt: now.toISOString(),
    host,
    reason:
      reason ?? 'Existing project config is JSONC or is not parseable as JSON; it was preserved unchanged.',
    patch: payload,
    nextAction:
      host === 'deepseek-harness'
        ? 'Create the local bundle files manually, then install/activate the bundle with DeepSeek Harness plugin tooling.'
        : host === 'opencode'
          ? 'Merge the generated server entry into mcp.servers in opencode.jsonc manually, then reload OpenCode.'
          : 'Merge the generated mcpServers entry into the existing project config manually, then reload the host.',
  };
  await atomicWrite(file, `${JSON.stringify(patch, null, 2)}\n`);
  return file;
}

async function readOptional(file) {
  try {
    return await fs.readFile(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

async function generateCordisBundle({ project, info, paths, now, host }) {
  const bundleDir = path.resolve(project, info.bundleDir);
  if (!isInside(project, bundleDir)) throw new ConfigError(`DSH bundle escapes project: ${bundleDir}`);
  const target = path.join(bundleDir, 'cordis.patch.yml');
  const packagePath = path.join(bundleDir, 'package.json');
  await assertProjectWrite(project, target);
  await assertProjectWrite(project, packagePath);
  const cordis = cordisPatch(paths);
  const packageText = bundlePackage();
  const existingCordis = await readOptional(target);
  const existingPackage = await readOptional(packagePath);
  let packageOwned = existingPackage === null;
  if (existingPackage !== null) {
    try {
      packageOwned = JSON.parse(existingPackage)?.name === BUNDLE_PACKAGE_NAME;
    } catch {
      packageOwned = false;
    }
  }
  const cordisOwned = existingCordis === null || existingCordis.includes(MARKER);
  if (!cordisOwned || !packageOwned) {
    const patchPath = await writePatch(
      project,
      host,
      {
        files: {
          'cordis.patch.yml': cordis,
          'package.json': packageText,
        },
      },
      now,
      'A non-generated file already exists in the DeepSeek Harness bundle directory; it was preserved unchanged.',
    );
    return {
      host,
      label: info.label,
      status: 'patch_required',
      nativeVerified: false,
      verification: 'schema-only',
      bundlePath: bundleDir,
      configPath: target,
      packagePath,
      patchPath,
      changed: false,
      reloadRequired: true,
      reload: info.reload,
      message:
        'An existing DeepSeek Harness bundle file was preserved. Merge the generated insert patch and package metadata manually.',
    };
  }
  const unchanged = existingCordis === cordis && existingPackage === packageText;
  let backupPaths = [];
  if (!unchanged) {
    if (existingCordis !== null) backupPaths.push(await backupFile(target, now));
    if (existingPackage !== null) backupPaths.push(await backupFile(packagePath, now));
    await fs.mkdir(bundleDir, { recursive: true });
    await atomicWrite(target, cordis);
    await atomicWrite(packagePath, packageText);
  }
  return {
    host,
    label: info.label,
    status: 'native_unverified',
    nativeVerified: false,
    verification: 'schema-only',
    bundlePath: bundleDir,
    configPath: target,
    packagePath,
    serverName: 'skill-conductor',
    changed: !unchanged,
    backupPaths,
    reloadRequired: true,
    reload: info.reload,
    message: unchanged
      ? 'The local DSH bundle already matches; no file was changed. Native installation/activation is still required.'
      : 'Generated a local DSH bundle with an - insert: Cordis patch and dsh.bundle.patch metadata. Native installation/activation is still required.',
  };
}

/**
 * Generate/merge only our MCP server into a project-owned host config. Never
 * writes a user/global host file, never prints existing values, and never
 * overwrites an unrelated server with the same name.
 */
export async function generateHostIntegration({
  host,
  cwd = process.cwd(),
  configPath,
  nodePath = process.execPath,
  cliPath = path.join(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), 'bin', 'skill-conductor.mjs'),
  now = new Date(),
} = {}) {
  const info = hostInfo(host);
  const project = path.resolve(cwd);
  const paths = {
    nodePath: path.resolve(nodePath),
    cliPath: path.resolve(cliPath),
    configPath: path.resolve(configPath),
  };

  if (info.format === 'cordis-yaml') {
    return generateCordisBundle({ project, info, paths, now, host });
  }

  const target = path.resolve(project, info.configPath);
  if (!isInside(project, target)) throw new ConfigError(`host config escapes project: ${target}`);
  await assertProjectWrite(project, target);
  const text = await readOptional(target);
  let raw = null;
  let unsupported = null;
  if (text === null && info.jsoncPath) {
    const jsoncTarget = path.resolve(project, info.jsoncPath);
    const jsoncText = await readOptional(jsoncTarget);
    if (jsoncText !== null) {
      // Do not create a second config next to an existing JSONC project file.
      const server = serverFor(host, paths);
      const patchPath = await writePatch(
        project,
        host,
        { mcp: { servers: { [SERVER_NAME]: server } } },
        now,
        `${info.jsoncPath} exists; it was preserved and a patch was generated instead of creating ${info.configPath}.`,
      );
      return {
        host,
        label: info.label,
        status: 'patch_required',
        nativeVerified: false,
        verification: 'schema-only',
        configPath: jsoncTarget,
        patchPath,
        changed: false,
        reloadRequired: true,
        message: `${info.jsoncPath} is JSONC and was preserved unchanged; merge the generated patch manually.`,
      };
    }
  }
  if (text !== null) {
    try {
      raw = JSON.parse(text.replace(/^\uFEFF/, ''));
    } catch (error) {
      unsupported = error.message;
    }
  }
  if (unsupported) {
    const server = serverFor(host, paths);
    const patchPath = await writePatch(
      project,
      host,
      host === 'opencode'
        ? { mcp: { servers: { [SERVER_NAME]: server } } }
        : { mcpServers: { [SERVER_NAME]: server } },
      now,
    );
    return {
      host,
      label: info.label,
      status: 'patch_required',
      nativeVerified: false,
      verification: 'schema-only',
      configPath: target,
      patchPath,
      changed: false,
      reloadRequired: true,
      message: `${info.configPath} is JSONC or invalid JSON and was preserved unchanged; merge the generated patch manually.`,
    };
  }

  const server = serverFor(host, paths);
  const choice = chooseServerName(host, raw);
  const next = mergedJson(host, raw, choice.name, server);
  if (text !== null && stableStringify(next) === stableStringify(raw)) {
    return {
      host,
      label: info.label,
      status: 'already_configured',
      nativeVerified: false,
      verification: 'schema-only',
      configPath: target,
      serverName: choice.name,
      preservedExistingConductor: Boolean(findOwnedServer(host, raw) && choice.name !== SERVER_NAME),
      changed: false,
      reloadRequired: true,
      reload: info.reload,
      message: 'The Skill Conductor MCP entry already matches; no file was changed.',
    };
  }
  let backupPath = null;
  if (text !== null) backupPath = await backupFile(target, now);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await atomicWrite(target, `${JSON.stringify(next, null, 2)}\n`);
  return {
    host,
    label: info.label,
    status: 'configured',
    nativeVerified: false,
    verification: 'schema-only',
    configPath: target,
    serverName: choice.name,
    preservedExistingConductor: choice.preservedConflict,
    backupPath,
    changed: true,
    reloadRequired: true,
    reload: info.reload,
    message: choice.preservedConflict
      ? `An unrelated mcpServers.${SERVER_NAME} entry was preserved. Added only "${choice.name}". Existing values were not printed.`
      : `Merged only the "${choice.name}" MCP server. Existing values were preserved and not printed.`,
  };
}

function extractServer(host, raw) {
  return findOwnedServer(host, raw)?.server ?? null;
}

function serverCommand(host, server) {
  return launchFor(host, server);
}

export function parseCordisCommand(text) {
  const lines = String(text).split(/\r?\n/);
  let command = null;
  const args = [];
  let inArgs = false;
  let argsIndent = null;
  for (const line of lines) {
    if (command === null) {
      const match = line.match(/^\s*command:\s*'((?:[^']|'')*)'\s*$/);
      if (match) command = match[1].replaceAll("''", "'");
    }
    const argsStart = line.match(/^(\s*)args:\s*$/);
    if (argsStart && !inArgs) {
      inArgs = true;
      argsIndent = argsStart[1].length;
      continue;
    }
    if (!inArgs) continue;
    const item = line.match(/^(\s*)-\s*'((?:[^']|'')*)'\s*$/);
    if (item && item[1].length > argsIndent) {
      args.push(item[2].replaceAll("''", "'"));
      continue;
    }
    if (line.trim() === '' || line.trim().startsWith('#')) continue;
    inArgs = false;
  }
  return command ? { command, args } : null;
}

/**
 * Launch the generated stdio command and perform an MCP initialize + tools/list
 * handshake. This is protocol evidence, not a claim that the native host app
 * was opened, reloaded or had the DSH bundle installed.
 */
export async function verifyHostIntegration({ host, cwd = process.cwd(), timeoutMs = 15000 } = {}) {
  const info = hostInfo(host);
  const target = path.resolve(cwd, info.configPath);
  const text = await fs.readFile(target, 'utf8');
  let launch = null;
  let serverName = null;
  if (info.format === 'cordis-yaml') {
    launch = parseCordisCommand(text);
    serverName = 'skill-conductor';
  } else {
    const raw = JSON.parse(text.replace(/^\uFEFF/, ''));
    const owned = findOwnedServer(host, raw);
    launch = serverCommand(host, owned?.server ?? null);
    serverName = owned?.name ?? null;
  }
  if (!launch) throw new ConfigError(`generated config does not contain a launchable stdio command: ${target}`);
  const child = spawn(launch.command, launch.args, {
    cwd,
    shell: false,
    windowsHide: true,
    stdio: ['pipe', 'pipe', 'pipe'],
  });
  let stdout = '';
  let stderr = '';
  let nonProtocol = 0;
  child.stdout.on('data', (chunk) => {
    stdout += chunk.toString('utf8');
  });
  child.stderr.on('data', (chunk) => {
    stderr += chunk.toString('utf8');
  });
  const closed = new Promise((resolve) => child.on('close', resolve));
  const send = (payload) => child.stdin.write(`${JSON.stringify(payload)}\n`);
  send({
    jsonrpc: '2.0',
    id: 1,
    method: 'initialize',
    params: { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'setup-verify', version: '1' } },
  });
  send({ jsonrpc: '2.0', method: 'notifications/initialized', params: {} });
  send({ jsonrpc: '2.0', id: 2, method: 'tools/list', params: {} });
  const timer = setTimeout(() => {
    try {
      child.kill();
    } catch {
      // already gone
    }
  }, timeoutMs);
  let init = null;
  let tools = null;
  const deadline = Date.now() + timeoutMs;
  let pending = '';
  while (Date.now() < deadline && (!init || !tools)) {
    const lines = (pending + stdout).split(/\r?\n/);
    pending = lines.pop() ?? '';
    stdout = '';
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      let message;
      try {
        message = JSON.parse(trimmed);
      } catch {
        nonProtocol += 1;
        continue;
      }
      if (message.id === 1) init = message;
      if (message.id === 2) tools = message;
    }
    if (!init || !tools) await new Promise((resolve) => setTimeout(resolve, 25));
  }
  clearTimeout(timer);
  child.stdin.end();
  await Promise.race([closed, new Promise((resolve) => setTimeout(resolve, 2000))]);
  if (!init || !tools) {
    throw new ConfigError(
      `generated host command did not complete the MCP handshake (init=${Boolean(init)}, tools=${Boolean(tools)})`,
      { nonProtocol, stderr: stderr.slice(0, 500) },
    );
  }
  return {
    host,
    serverName,
    status: 'protocol_verified',
    nativeVerified: false,
    verification: 'stdio-handshake',
    serverInfo: init.result?.serverInfo ?? null,
    toolCount: Array.isArray(tools.result?.tools) ? tools.result.tools.length : 0,
    stdoutProtocolOnly: nonProtocol === 0,
    nonProtocolLines: nonProtocol,
    note: 'Generated command+args launched and completed initialize/tools/list. The native host application and DSH bundle installation were not automated.',
  };
}

/**
 * Presence-only inspection. It does not return config values that might contain
 * credentials. Used by doctor/health.
 */
export async function inspectHostIntegrations({ cwd = process.cwd() } = {}) {
  const result = [];
  for (const [host, info] of Object.entries(HOSTS)) {
    const target = path.resolve(cwd, info.configPath);
    let present = false;
    let configured = false;
    let format = info.format;
    let serverName = null;
    try {
      const text = await fs.readFile(target, 'utf8');
      present = true;
      if (info.format === 'cordis-yaml') {
        configured = text.includes('id: mcp-skill-conductor') && text.includes('@deepseek-ai/dsh-mcp-client');
        if (configured) serverName = 'skill-conductor';
      } else {
        const raw = JSON.parse(text.replace(/^\uFEFF/, ''));
        const owned = findOwnedServer(host, raw);
        configured = Boolean(owned);
        serverName = owned?.name ?? null;
      }
    } catch {
      configured = false;
    }
    if (!present && info.jsoncPath) {
      const jsonc = path.resolve(cwd, info.jsoncPath);
      try {
        await fs.readFile(jsonc, 'utf8');
        present = true;
        format = 'jsonc';
        configured = false;
        serverName = null;
      } catch {
        // absent
      }
    }
    result.push({
      host,
      label: info.label,
      path: target,
      present,
      configured,
      serverName,
      format,
      reloadRequired: configured,
      nativeVerified: false,
      verification: configured ? 'schema-only' : 'not-configured',
    });
  }
  return result;
}

